"""eljazari.ai — Phase 8: Real MAVSDK code template.

Generates production-ready PX4 mission code using the *real* MAVSDK API
surface (``drone.action``, ``drone.mission``, ``drone.telemetry``,
``drone.geofence``) — no internal "skill API" adapter required.

The output of :func:`render_real_mavsdk_mission` is a complete, runnable
Python script that:

  1. Reads the MAVSDK endpoint from ``DRONEPROMPT_MAVSDK_ADDRESS`` (PX4 SITL
     default ``udpin://0.0.0.0:14540``; HITL uses the serial port URI).
  2. Waits for ``drone.core.connection_state()`` to confirm the link.
  3. Waits for ``drone.telemetry.health()`` until ``is_global_position_ok``
     and ``is_home_position_ok`` are true (or 30 s elapse — then aborts).
  4. Optionally uploads a geofence built from the GSCE constraints.
  5. Sets takeoff altitude, arms, takes off, and waits for the climb.
  6. Uploads the :class:`MissionPlan` and starts it.
  7. Waits until progress is complete and PX4 has left MISSION mode itself.
  8. Returns to launch.

The template is intentionally a *string template* (not a code generator
function) so the resulting Python file is human-readable and can be
inspected, edited, and version-controlled side-by-side with the URDF.

Safety injections (battery monitor, connection watchdog, geofence guard,
emergency handler) are applied *after* template render by
``agents.safety_layer`` — they layer on top without modifying the core
mission, which keeps the generated script's intent legible.
"""

