_HELPERS = '''
async def wait_for_connection(drone: System, timeout_s: float = CONNECTION_TIMEOUT_S) -> None:
    """Block until the MAVSDK connection state reports connected, or raise."""
    deadline = asyncio.get_event_loop().time() + timeout_s
    async for state in drone.core.connection_state():
        if state.is_connected:
            logger.info("mavsdk.connected", extra={"address": MAVSDK_ADDRESS})
            return
        if asyncio.get_event_loop().time() > deadline:
            raise TimeoutError("MAVSDK connection state did not report connected")


async def wait_for_global_position(drone: System, timeout_s: float = GLOBAL_POSITION_TIMEOUT_S) -> None:
    """Block until the EKF reports a valid global position and a home fix."""
    deadline = asyncio.get_event_loop().time() + timeout_s
    async for health in drone.telemetry.health():
        if health.is_global_position_ok and health.is_home_position_ok:
            logger.info("mavsdk.global_position_ok")
            return
        if asyncio.get_event_loop().time() > deadline:
            raise TimeoutError("Global position estimate not available")


async def get_battery_pct(drone: System) -> float:
    """Return the current battery state-of-charge in percent (0-100)."""
    async for battery in drone.telemetry.battery():
        remaining = float(getattr(battery, "remaining_percent", 0.0) or 0.0)
        return remaining * 100.0 if remaining <= 1.0 else remaining
    return 0.0


async def check_pre_flight(drone: System, timeout_s: float = 60.0) -> None:
    """Wait for calibration, GPS, and arm health to converge before launch.

    In SITL the EKF needs ~15-30 s after boot before ``is_armable`` flips true
    (the first health samples report 'ekf2 missing data' / 'heading estimate
    invalid'). Reading only the FIRST sample and bailing is the classic
    mistake — here we poll until the vehicle is actually armable, up to
    ``timeout_s``, instead of giving up on a cold EKF.
    """
    loop = asyncio.get_event_loop()
    deadline = loop.time() + timeout_s
    reason = "no telemetry"
    async for health in drone.telemetry.health():
        gyro_ok = bool(getattr(health, "is_gyrometer_calibration_ok", True))
        accel_ok = bool(getattr(health, "is_accelerometer_calibration_ok", True))
        pos_ok = bool(getattr(health, "is_global_position_ok", False))
        home_ok = bool(getattr(health, "is_home_position_ok", False))
        armable = bool(getattr(health, "is_armable", False))
        # The real arming gate is a converged EKF: global + home position OK.
        # ``is_armable`` is not populated reliably across MAVSDK versions, so
        # accept it as sufficient but do not require it.
        if gyro_ok and accel_ok and (armable or (pos_ok and home_ok)):
            break
        if not gyro_ok:
            reason = "gyro calibration not OK"
        elif not accel_ok:
            reason = "accel calibration not OK"
        else:
            reason = "global/home position not ready (EKF still converging)"
        if loop.time() > deadline:
            raise RuntimeError(f"Pre-flight failed after {timeout_s:.0f}s: {reason}")
        await asyncio.sleep(1.0)
    deadline = loop.time() + timeout_s
    async for gps in drone.telemetry.gps_info():
        fix = getattr(gps, "fix_type", None)
        fix_name = getattr(fix, "name", str(fix))
        sats = int(getattr(gps, "num_satellites", 0) or 0)
        # MAVSDK's FixType enum is NOT int-convertible — int(FixType.FIX_3D)
        # raises TypeError. Compare by enum name instead (FIX_3D, FIX_DGPS,
        # RTK_FLOAT, RTK_FIXED all qualify; FIX_2D does not contain "3D").
        fix_ok = ("3D" in fix_name) or ("DGPS" in fix_name) or ("RTK" in fix_name)
        if fix_ok and sats >= 6:
            break
        if loop.time() > deadline:
            raise RuntimeError(
                f"Pre-flight failed: GPS not ready (fix={fix_name}, sats={sats})"
            )
        await asyncio.sleep(1.0)
    battery_pct = await get_battery_pct(drone)
    if battery_pct < MIN_BATTERY_PCT_TAKEOFF:
        raise RuntimeError(
            f"Pre-flight failed: battery {battery_pct:.1f}% < {MIN_BATTERY_PCT_TAKEOFF}%"
        )
    logger.info("preflight.ok", extra={"battery_pct": battery_pct})


async def upload_circular_geofence(
    drone: System,
    radius_m: float,
    max_alt_m: float = 120.0,
) -> None:
    """Enforce a cylindrical geofence around the launch point via PX4 params.

    The MAVLink polygon-fence upload (drone.geofence.upload_geofence) returns a
    generic error on the PX4 + gz SITL build and, run before the mission,
    corrupts the shared mission protocol. PX4's built-in geofence is set with
    parameters instead — a cylinder of horizontal radius `radius_m` and height
    `max_alt_m` around home, with return-to-launch on breach. The commander
    enforces these directly, with no mission-protocol upload, so it works in
    SITL and never interferes with the mission upload.
    """
    await drone.param.set_param_int("GF_ACTION", 3)  # 3 = return-to-launch on breach
    await drone.param.set_param_float("GF_MAX_HOR_DIST", float(radius_m))
    await drone.param.set_param_float("GF_MAX_VER_DIST", float(max_alt_m))
    logger.info("geofence.params_set", extra={"radius_m": radius_m, "max_alt_m": max_alt_m})


async def wait_for_takeoff_complete(drone: System, target_alt_m: float, timeout_s: float = 30.0) -> None:
    """Block until the altitude above home reaches 95% of target.

    Measured above home, the frame PX4's takeoff target uses. The local NED origin
    is where the estimator started, which barometer drift before arming can put
    tenths of a metre off: a hexacopter holding 4.85 m above home read 4.64 m in
    that frame and timed out against a 4.75 m threshold.
    """
    deadline = asyncio.get_event_loop().time() + timeout_s
    async for position in drone.telemetry.position():
        altitude_m = position.relative_altitude_m
        if altitude_m >= target_alt_m * 0.95:
            logger.info("takeoff.complete", extra={"altitude_m": altitude_m})
            return
        if asyncio.get_event_loop().time() > deadline:
            raise TimeoutError(f"Takeoff did not reach {target_alt_m}m")


async def anchor_mission_to_home(drone: System, items: list) -> None:
    """Move waypoints planned around PLANNED_HOME onto the vehicle's actual home.

    The plan is NED offsets from takeoff; its absolute coordinates were computed
    around a nominal home. A simulator world or field site with a different home
    would otherwise send the vehicle tens of metres away, and PX4 rejects such a
    mission against the geofence, leaving the vehicle holding until timeout.
    """
    # Module constants rendered alongside the mission items.
    planned_lat = PLANNED_HOME_LATITUDE_DEG
    planned_lon = PLANNED_HOME_LONGITUDE_DEG
    async for home in drone.telemetry.home():
        break
    lon_scale = math.cos(math.radians(planned_lat)) / max(
        math.cos(math.radians(home.latitude_deg)), 1e-6
    )
    for item in items:
        item.latitude_deg = home.latitude_deg + (item.latitude_deg - planned_lat)
        item.longitude_deg = home.longitude_deg + (item.longitude_deg - planned_lon) * lon_scale
    logger.info(
        "mission.anchored_to_home",
        extra={"home_lat": home.latitude_deg, "home_lon": home.longitude_deg},
    )


async def run_mission_progress(drone: System, total_items: int) -> str:
    """Wait until PX4 has flown the mission: "complete", "left" or "not_started".

    MAVSDK's progress can briefly report current == total about half a second
    after the start, when item-reached messages overtake MISSION_CURRENT, and
    correct itself a moment later. Trusting that report cut a 15 s hover to
    about 2 s in 5 of 17 SITL flights. PX4's flight mode decides instead: the
    mission is complete when progress says so and PX4 has left MISSION mode on
    its own. Leaving MISSION mode before the end is "left": a failsafe (battery,
    geofence, estimator) took over. Not entering it within
    MISSION_START_TIMEOUT_S is "not_started": PX4 refused the mission.
    """
    state = {"complete": False, "mode": None, "px4": ""}

    async def watch_progress() -> None:
        async for progress in drone.mission.mission_progress():
            logger.info("mission.progress current=%d total=%d", progress.current, progress.total)
            state["complete"] = progress.current >= progress.total

    async def watch_mode() -> None:
        async for mode in drone.telemetry.flight_mode():
            state["mode"] = mode

    async def watch_status() -> None:
        # PX4's own account of a failsafe or a refusal, kept for the error line.
        async for status in drone.telemetry.status_text():
            logger.info("px4.status %s: %s", status.type, status.text)
            state["px4"] = status.text

    asyncio.create_task(watch_progress())
    asyncio.create_task(watch_mode())
    asyncio.create_task(watch_status())
    loop = asyncio.get_event_loop()
    started = loop.time()
    seen_mission = False
    complete_since = None
    left_since = None
    while True:
        await asyncio.sleep(0.2)
        now = loop.time()
        in_mission = state["mode"] == FlightMode.MISSION
        seen_mission = seen_mission or in_mission
        if state["complete"]:
            complete_since = complete_since if complete_since is not None else now
            settled = not seen_mission and now - complete_since >= MISSION_SETTLE_S
            if (seen_mission and not in_mission) or settled:
                logger.info("mission.complete mode=%s", state["mode"])
                return "complete"
        else:
            complete_since = None
        if seen_mission and not in_mission:
            left_since = left_since if left_since is not None else now
            if not state["complete"] and now - left_since >= MISSION_SETTLE_S:
                logger.error(
                    "mission.left_mode_incomplete mode=%s px4=%s", state["mode"], state["px4"]
                )
                return "left"
        else:
            left_since = None
        if not seen_mission and not state["complete"] and now - started >= MISSION_START_TIMEOUT_S:
            logger.error("mission.not_started mode=%s px4=%s", state["mode"], state["px4"])
            return "not_started"


async def wait_until_landed(drone: System, timeout_s: float) -> bool:
    """Block until PX4 reports the vehicle on the ground, or timeout_s passes."""

    async def on_ground() -> None:
        async for landed in drone.telemetry.landed_state():
            if landed == LandedState.ON_GROUND:
                return

    try:
        await asyncio.wait_for(on_ground(), timeout=timeout_s)
    except asyncio.TimeoutError:
        logger.error("landing.timeout after %.0f s", timeout_s)
        return False
    logger.info("landed")
    return True
'''


