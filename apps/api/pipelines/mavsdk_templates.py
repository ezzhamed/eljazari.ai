def render_real_mavsdk_mission(
    spec: MissionPlanSpec,
    *,
    geofence_radius_m: float | None = 250.0,
    rtl_altitude_m: float | None = None,
) -> str:
    """Render a complete, runnable Python file implementing the mission.

    Args:
        spec: high-level mission plan in NED-typed waypoints.
        geofence_radius_m: if set, upload a circular geofence of this radius.
        rtl_altitude_m: if set, configure the PX4 ``RTL_RETURN_ALT`` to this.

    Returns:
        The full Python source, ready to ``exec`` or write to disk.
    """
    body = _MISSION_BODY.format(
        mission_items_block=render_mission_items_python(spec),
        planned_home_lat=f"{spec.home.lat_deg:.7f}",
        planned_home_lon=f"{spec.home.lon_deg:.7f}",
        takeoff_alt_m=f"{spec.takeoff_altitude_m:.2f}",
        use_geofence=str(geofence_radius_m is not None),
        geofence_radius_m=f"{geofence_radius_m:.2f}" if geofence_radius_m else "0.0",
        use_rtl_alt=str(rtl_altitude_m is not None),
        rtl_alt_m=f"{rtl_altitude_m:.2f}" if rtl_altitude_m else "0.0",
        rtl_after_mission=str(spec.return_to_launch_after_mission),
    )
    return _HEADER + _HELPERS + body


def render_home_position_constants(home: LLA) -> str:
    """Render a small constants block embedding the home LLA in code."""
    return (
        f"# Default home position (PX4 SITL convention)\n"
        f"HOME_LATITUDE_DEG = {home.lat_deg:.7f}\n"
        f"HOME_LONGITUDE_DEG = {home.lon_deg:.7f}\n"
        f"HOME_ALTITUDE_M = {home.alt_m:.2f}\n"
    )
