_MISSION_BODY = '''
{mission_items_block}

# Waypoints above are NED offsets from this nominal home; run_mission re-anchors
# them on the vehicle's actual home before upload.
PLANNED_HOME_LATITUDE_DEG = {planned_home_lat}
PLANNED_HOME_LONGITUDE_DEG = {planned_home_lon}


async def run_mission(drone: System) -> bool:
    """Execute the planned mission. Returns True iff completed successfully."""
    try:
        await check_pre_flight(drone)
    except Exception as exc:
        logger.error("preflight.failed: %s", exc)
        return False

    await anchor_mission_to_home(drone, mission_items)
    await drone.action.set_takeoff_altitude({takeoff_alt_m})
    if {use_rtl_alt}:
        await drone.action.set_return_to_launch_altitude({rtl_alt_m})

    # Set the optional geofence via PX4 params (cylinder around home) — it does
    # not use the mission protocol, so order no longer matters and it cannot
    # corrupt the mission upload. Then upload the mission.
    if {use_geofence}:
        try:
            await upload_circular_geofence(drone, radius_m={geofence_radius_m})
        except Exception as exc:
            logger.warning("geofence.skip: %s", exc)

    plan = MissionPlan(mission_items)
    await drone.mission.set_return_to_launch_after_mission({rtl_after_mission})
    try:
        await drone.mission.clear_mission()
    except Exception:
        pass

    # PX4 can reject the first upload while its mission manager is still
    # settling — the console shows "REJ. MIS ITEM: partner id mismatch" followed
    # by "Mission sync timeout", surfacing here as MissionError PROTOCOL_ERROR.
    # It succeeds on a retry once the link has stabilised.
    for attempt in range(1, 4):
        try:
            await drone.mission.upload_mission(plan)
            break
        except Exception as exc:
            if attempt == 3:
                logger.error("mission.upload_failed after %d attempts: %s", attempt, exc)
                raise
            logger.warning("mission.upload_retry attempt=%d: %s", attempt, exc)
            await asyncio.sleep(2.0 * attempt)

    # PX4 refuses to arm until its own preflight checks pass, and one of them is
    # "No connection to the GCS" — which only clears once this script has
    # connected. So the vehicle becomes armable a few seconds *after* we attach,
    # never before. A single attempt raced that window and returned
    # COMMAND_DENIED; retry until PX4 has settled.
    logger.info("arming")
    for attempt in range(1, 11):
        try:
            await drone.action.arm()
            logger.info("arm.ok attempt=%d", attempt)
            break
        except ActionError as exc:
            if attempt == 10:
                logger.error("arm.failed after %d attempts: %s", attempt, exc)
                return False
            logger.warning("arm.retry attempt=%d: %s", attempt, exc)
            await asyncio.sleep(3.0)

    logger.info("takeoff", extra={{"target_alt_m": {takeoff_alt_m}}})
    await drone.action.takeoff()
    await wait_for_takeoff_complete(drone, target_alt_m={takeoff_alt_m})

    logger.info("mission.start")
    try:
        await drone.mission.start_mission()
        outcome = await run_mission_progress(drone, total_items=len(mission_items))
    except MissionError as exc:
        logger.error("mission.failed: %s", exc)
        outcome = "not_started"
    if outcome == "left":
        # PX4 left the mission on its own: its failsafe (battery, geofence,
        # estimator) is in charge. A return commanded now would override it; on
        # an empty battery that climbed from 10 m to 26 m in SITL.
        # A warning: the error line above (mode and PX4's text) is the reason.
        logger.warning("mission.failsafe: PX4 is in charge, watching it land")
        await wait_until_landed(drone, LANDING_TIMEOUT_S)
        return False
    if outcome != "complete":
        # PX4 never flew the mission; the vehicle holds where takeoff left it.
        try:
            await drone.action.return_to_launch()
        except ActionError:
            await drone.action.land()
        await wait_until_landed(drone, LANDING_TIMEOUT_S)
        return False

    if {rtl_after_mission}:
        logger.info("return_to_launch")
        await drone.action.return_to_launch()

    if not await wait_until_landed(drone, LANDING_TIMEOUT_S):
        return False
    logger.info("mission.success")
    return True


async def main() -> int:
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s %(name)s %(levelname)s %(message)s",
    )
    drone = System()
    await drone.connect(system_address=MAVSDK_ADDRESS)
    await wait_for_connection(drone)
    await wait_for_global_position(drone)
    ok = await run_mission(drone)
    return 0 if ok else 1


def _install_signal_handlers() -> None:
    def _handle(signum, _frame):
        logger.error("signal.received", extra={{"signum": signum}})
        sys.exit(2)
    for sig in (signal.SIGINT, signal.SIGTERM):
        try:
            signal.signal(sig, _handle)
        except (ValueError, OSError):
            pass


if __name__ == "__main__":
    _install_signal_handlers()
    sys.exit(asyncio.run(main()))
'''


